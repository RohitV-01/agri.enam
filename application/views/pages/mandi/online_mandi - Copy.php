function load_first1(){
$.ajax({
		type : 'POST',
		//url : 'http://www.enam.gov.in/NamWebSrv/rest/liveBidding/stateWise',
		url : 'https://train.enam.gov.in/NamWebSrv/rest/getActiveState',
		data : {
			'orgId' : 1,
			'newOldMandiFlag' : 'N',
			'language' : 'en',
                        'fromDate' : $('#curr_date1').val() + ' 00:00:00',
                        'toDate' : $('#curr_date1').val() + ' 23:59:59'  
		},
		success : function (response1){
			local_data1 = response1;

			create_table1(c1);
			$.each(response1.listActiveState, function(key1,value1){ 
				var stateName1 = value1.stateName.toUpperCase().split(' ').join('_');
		
				if(value1.activeCount != '0'){
					$('#'+ stateName1+'1').find('strong').css({"background-image":"url("+baseUrl+"assest/images/green-lamp.png)","background-repeat":"no-repeat"});
				}
				else{
					$('#'+ stateName1+'1').find('strong').css({"background-image":"url("+baseUrl+"assest/images/red-lamp.png)","background-repeat":"no-repeat"});
				}
			total_apmc1 = parseInt(parseInt(total_apmc1) + parseInt(value1.oprCount));
			total_mol1 =  parseInt(parseInt(total_mol1)  + parseInt(value1.activeCount));
			});
		}
	});
}

